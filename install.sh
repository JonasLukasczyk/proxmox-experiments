#!/usr/bin/env bash

# Stop immediately on errors, unset variables, or failed pipeline commands.
set -euo pipefail

###############################################################################
# Proxmox smart-PXE provisioning server
#
# Services:
#   dnsmasq  - DHCP, PXE options and TFTP
#   nginx    - Public HTTP endpoint and large static files
#   Node.js  - Dynamic iPXE decisions and Proxmox answer files
#
# Network:
#   Provisioning host: 192.168.50.1/24
#   DHCP clients:       192.168.50.100-150
###############################################################################

###############################################################################
# 1. Configuration
###############################################################################

# Set this to the dedicated Ethernet interface connected to the target device.
# It must not be the interface connected to the office LAN.
export LINK="enp0s20f0u6u1c2"

PROVISION_IP="192.168.50.1"
PROVISION_CIDR="${PROVISION_IP}/24"
DHCP_START="192.168.50.100"
DHCP_END="192.168.50.150"

# Confirm that the selected interface exists before changing anything.
if ! ip link show "${LINK}" >/dev/null 2>&1; then
    echo "Error: network interface '${LINK}' does not exist." >&2
    echo "Available interfaces:" >&2
    ip -br link >&2
    exit 1
fi

###############################################################################
# 2. Configure the dedicated provisioning interface
###############################################################################

# Bring the interface up and assign the provisioning address.
#
# The address is temporary and will disappear after reboot. It can later be
# made persistent with NetworkManager, systemd-networkd or another host network
# configuration system.
sudo ip link set "${LINK}" up
sudo ip addr flush dev "${LINK}"
sudo ip addr add "${PROVISION_CIDR}" dev "${LINK}"

echo "Provisioning interface:"
ip -br addr show "${LINK}"

# A working cable and powered target should cause LOWER_UP to appear.
echo
echo "Physical-link status:"
sudo ethtool "${LINK}" | grep -E 'Speed:|Duplex:|Link detected:' || true

###############################################################################
# 3. Create the project directories
###############################################################################

mkdir -p \
    builder \
    builder/tmp \
    config/dnsmasq \
    config/nginx \
    app/src \
    data/dnsmasq \
    data/inventory \
    data/tftp \
    data/iso \
    data/http/proxmox \
    data/http/static \
    data/http/answers


# dnsmasq writes leases into this bind-mounted directory.
touch data/dnsmasq/dnsmasq.leases

###############################################################################
# 4. Create the Compose environment file
###############################################################################

cat > .env <<EOF
PROVISION_INTERFACE=${LINK}
PROVISION_IP=${PROVISION_IP}
PROVISION_SUBNET=192.168.50.0/24
DHCP_START=${DHCP_START}
DHCP_END=${DHCP_END}
EOF

###############################################################################
# 5. Configure nginx
###############################################################################

cat > config/nginx/default.conf <<'EOF'
server {
    listen 80;
    server_name _;

    access_log /var/log/nginx/access.log;
    error_log  /var/log/nginx/error.log;

    # Simple landing page and other files in data/http/.
    location / {
        root /usr/share/nginx/html;
        index index.html;
    }

    # Large Proxmox installer payloads are served directly by nginx.
    location /proxmox/ {
        root /usr/share/nginx/html;
        sendfile on;
    }

    # Additional static files, if needed.
    location /static/ {
        root /usr/share/nginx/html;
        sendfile on;
    }

    # Dynamic iPXE scripts generated by the Node.js API.
    #
    # Because proxy_pass has no path component, nginx forwards the complete
    # original URI, including /ipxe/boot and its query string.
    location /ipxe/ {
        proxy_pass http://api:3000;
        proxy_http_version 1.1;

        proxy_set_header Host              $host;
        proxy_set_header X-Real-IP         $remote_addr;
        proxy_set_header X-Forwarded-For   $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
    }

    # Dynamic Proxmox answer files generated by the Node.js API.
    location /answer {
        proxy_pass http://api:3000;
        proxy_http_version 1.1;

        proxy_set_header Host              $host;
        proxy_set_header X-Real-IP         $remote_addr;
        proxy_set_header X-Forwarded-For   $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
    }

    # API health check, exposed through the single public HTTP endpoint.
    location = /health {
        proxy_pass http://api:3000/health;
        proxy_http_version 1.1;
    }
}
EOF

###############################################################################
# 6. Create a basic nginx landing page
###############################################################################

cat > data/http/index.html <<'EOF'
<!doctype html>
<html lang="en">
<head>
    <meta charset="utf-8">
    <title>Proxmox Provisioner</title>
</head>
<body>
    <h1>Proxmox provisioning server is running</h1>
</body>
</html>
EOF

###############################################################################
# 7. Create the initial host inventory
###############################################################################

cat > data/inventory/hosts.json <<'EOF'
{}
EOF

###############################################################################
# 8. Create the dnsmasq image
###############################################################################

cat > config/dnsmasq/Dockerfile <<'EOF'
FROM alpine:3.22

RUN apk add --no-cache dnsmasq

ENTRYPOINT ["dnsmasq"]
CMD ["--no-daemon", "--conf-file=/etc/dnsmasq.conf"]
EOF

###############################################################################
# 9. Configure DHCP, TFTP and PXE
###############################################################################

# This heredoc is intentionally unquoted because ${LINK}, ${DHCP_START} and
# ${DHCP_END} must be resolved while this file is generated.
cat > config/dnsmasq/dnsmasq.conf <<EOF
# Listen only on the dedicated provisioning interface.
interface=${LINK}
bind-interfaces

# Disable dnsmasq's DNS server. Only DHCP and TFTP are needed.
port=0

# Address pool for PXE clients.
dhcp-range=${DHCP_START},${DHCP_END},255.255.255.0,1h

# Do not advertise a default gateway on this isolated provisioning network.
dhcp-option=option:router

# DHCP diagnostics are written to the container log.
log-dhcp
log-facility=-

# Persistent lease database.
dhcp-leasefile=/var/lib/misc/dnsmasq.leases

# Serve the initial iPXE loader over TFTP.
enable-tftp
tftp-root=/srv/tftp

# The Dell reports UEFI x86-64 architecture 00007.
# ipxe.efi is therefore used as its initial network boot program.
dhcp-boot=ipxe.efi
EOF

###############################################################################
# 10. Download the UEFI iPXE loader
###############################################################################

curl --fail --location \
    https://boot.ipxe.org/x86_64-efi/ipxe.efi \
    --output data/tftp/ipxe.efi

# Confirm that the downloaded file is an EFI executable.
file data/tftp/ipxe.efi

###############################################################################
# 11. Create the iPXE bootstrap script
###############################################################################

# The downloaded iPXE binary loads autoexec.ipxe from the TFTP directory.
#
# This file has only one long-term responsibility:
# hand control from TFTP to the HTTP smart-PXE endpoint.
#
# The heredoc must remain quoted so that ${net0/mac} and ${errno} are evaluated
# by iPXE on the target, not by this shell.
cat > data/tftp/autoexec.ipxe <<'EOF'
#!ipxe

echo Contacting smart PXE server...

# The firmware DHCP lease does not always carry cleanly into iPXE, so request
# network configuration again before contacting the HTTP server.
dhcp || goto failed

# nginx receives this request on port 80 and proxies it to the Node.js API.
chain http://192.168.50.1/ipxe/boot?mac=${net0/mac} || goto failed

:failed
echo Dynamic PXE request failed
echo iPXE error: ${errno}
shell
EOF

# step iso
ISO_FILE="proxmox-ve_9.2-1.iso"
ISO_DIR="./data/iso"
ISO_URL="http://download.proxmox.com/iso/${ISO_FILE}"

if [[ ! -f "${ISO_DIR}/${ISO_FILE}" ]]; then
    echo "Downloading Proxmox ISO..."
    curl --fail --location \
        "${ISO_URL}" \
        --output "${ISO_DIR}/${ISO_FILE}"
else
    echo "Proxmox ISO already exists: ${ISO_DIR}/${ISO_FILE}"
fi

###############################################################################
# 12. Create the Node.js container image
###############################################################################

# The following files must also exist:
#   app/package.json
#   app/src/server.js
#
# They are intentionally not generated here because the application contents
# are maintained separately.
cat > app/Dockerfile <<'EOF'
FROM node:24-alpine

WORKDIR /app

# Install production dependencies before copying the source so Docker can cache
# the dependency layer when only application code changes.
COPY package.json ./
RUN npm install --omit=dev

COPY src ./src

# Drop root privileges before starting the application.
USER node

CMD ["npm", "start"]
EOF

# Fail early if the separately maintained application files are missing.
for required_file in app/package.json app/src/server.js; do
    if [[ ! -f "${required_file}" ]]; then
        echo "Error: required Node.js file is missing: ${required_file}" >&2
        exit 1
    fi
done

###############################################################################
# 13. Create Docker Compose configuration
###############################################################################

# This heredoc must remain quoted.
#
# Docker Compose, rather than this shell, resolves ${PROVISION_IP} from .env.
cat > compose.yaml <<'EOF'
services:
  builder:
    build:
      context: ./builder
    container_name: proxmox-builder
    profiles:
      - build
    volumes:
      - ./data/iso:/workspace/iso:ro
      - ./builder:/workspace/builder:ro
      - ./builder/tmp:/workspace/tmp
      - ./data/http/proxmox:/workspace/output
  api:
    build:
      context: ./app
    container_name: proxmox-api
    restart: unless-stopped

    # Port 3000 is visible only to containers on the Compose network.
    expose:
      - "3000"

    environment:
      HOST: "0.0.0.0"
      PORT: "3000"
      INVENTORY_PATH: "/data/inventory/hosts.json"

    volumes:
      - ./data/inventory:/data/inventory

  nginx:
    image: nginx:1.29-alpine
    container_name: proxmox-nginx
    restart: unless-stopped

    depends_on:
      - api

    # nginx is the only public HTTP server.
    # Binding to PROVISION_IP prevents exposure on the office-facing NIC.
    ports:
      - "${PROVISION_IP}:80:80"

    volumes:
      - ./config/nginx/default.conf:/etc/nginx/conf.d/default.conf:ro
      - ./data/http:/usr/share/nginx/html:ro

  dnsmasq:
    build:
      context: ./config/dnsmasq
    container_name: proxmox-dnsmasq
    restart: unless-stopped

    # DHCP broadcasts and the physical host interface require host networking.
    network_mode: host

    cap_add:
      - NET_ADMIN
      - NET_RAW

    volumes:
      - ./config/dnsmasq/dnsmasq.conf:/etc/dnsmasq.conf:ro
      - ./data/tftp:/srv/tftp:ro
      - ./data/dnsmasq:/var/lib/misc
EOF

###############################################################################
# 14. Validate the generated configuration
###############################################################################

echo
echo "Validating Docker Compose configuration..."
sudo docker compose config >/dev/null

echo "Compose configuration is valid."



###############################################################################
# 14.5. Builder
###############################################################################

cat > builder/Dockerfile <<'EOF'
FROM debian:trixie-slim

ENV DEBIAN_FRONTEND=noninteractive

# Base tools needed to configure APT and prepare Proxmox installation media.
RUN apt-get update \
    && apt-get install -y --no-install-recommends \
        ca-certificates \
        curl \
        gpg \
        xorriso \
    && rm -rf /var/lib/apt/lists/*

# Install the official Proxmox Trixie repository signing key.
RUN curl --fail --location \
        https://enterprise.proxmox.com/debian/proxmox-archive-keyring-trixie.gpg \
        --output /usr/share/keyrings/proxmox-archive-keyring.gpg

# The no-subscription repository is suitable for this build/test tooling.
# A subscription repository could be substituted in managed environments.
RUN printf '%s\n' \
      'Types: deb' \
      'URIs: http://download.proxmox.com/debian/pve' \
      'Suites: trixie' \
      'Components: pve-no-subscription' \
      'Signed-By: /usr/share/keyrings/proxmox-archive-keyring.gpg' \
      > /etc/apt/sources.list.d/proxmox.sources

RUN apt-get update \
    && apt-get install -y --no-install-recommends \
        proxmox-auto-install-assistant \
    && rm -rf /var/lib/apt/lists/*

WORKDIR /workspace

COPY build.sh /usr/local/bin/build-proxmox-pxe

RUN chmod 0755 /usr/local/bin/build-proxmox-pxe

ENTRYPOINT ["build-proxmox-pxe"]
EOF

cat > builder/build.sh <<'EOF'
#!/usr/bin/env bash

set -euo pipefail

ISO_DIR="/workspace/iso"
OUTPUT_DIR="/workspace/output"
TMP_DIR="/workspace/tmp"
ANSWER_URL="${ANSWER_URL:-http://192.168.50.1/answer}"

mapfile -t ISO_FILES < <(
    find "${ISO_DIR}" \
        -maxdepth 1 \
        -type f \
        -name 'proxmox-ve_*.iso' \
        | sort
)

if [[ "${#ISO_FILES[@]}" -ne 1 ]]; then
    echo "Expected exactly one Proxmox ISO in ${ISO_DIR}." >&2
    echo "Found ${#ISO_FILES[@]} ISO files:" >&2
    printf '  %s\n' "${ISO_FILES[@]:-none}" >&2
    exit 1
fi

ISO_PATH="${ISO_FILES[0]}"

echo "Using ISO:"
echo "  ${ISO_PATH}"
echo
echo "Answer endpoint:"
echo "  ${ANSWER_URL}"
echo
echo "Output directory:"
echo "  ${OUTPUT_DIR}"
echo
echo "Temporary directory:"
echo "  ${TMP_DIR}"
echo

mkdir -p "${OUTPUT_DIR}" "${TMP_DIR}"

find "${OUTPUT_DIR}" \
    -mindepth 1 \
    -maxdepth 1 \
    -exec rm -rf -- {} +

find "${TMP_DIR}" \
    -mindepth 1 \
    -maxdepth 1 \
    -exec rm -rf -- {} +

if ! proxmox-auto-install-assistant prepare-iso \
    "${ISO_PATH}" \
    --fetch-from http \
    --url "${ANSWER_URL}" \
    --pxe-loader ipxe \
    --tmp "${TMP_DIR}" \
    --output "${OUTPUT_DIR}"
then
    echo "Error: PXE artifact generation failed." >&2
    exit 1
fi

echo
echo "Generated PXE artifacts:"

find "${OUTPUT_DIR}" \
    -maxdepth 2 \
    -type f \
    -printf '  %P (%s bytes)\n' \
    | sort
EOF

chmod +x builder/build.sh
mkdir -p builder/tmp
echo 'builder/tmp/' >> .gitignore

echo "Stopping existing provisioning stack..."
sudo docker compose down --remove-orphans

echo "Building PXE artifacts..."
sudo docker compose --profile build build builder
sudo docker compose --profile build run --rm builder

echo "Starting provisioning stack..."
sudo docker compose up --detach --build

###############################################################################
# 16. Verify the services
###############################################################################

echo
echo "Container status:"
sudo docker compose ps

echo
echo "dnsmasq startup log:"
sudo docker compose logs --tail=30 dnsmasq

echo
echo "Node.js API startup log:"
sudo docker compose logs --tail=30 api

echo
echo "nginx startup log:"
sudo docker compose logs --tail=30 nginx

###############################################################################
# 17. Verify HTTP routing
###############################################################################

echo "Waiting for provisioning server..."

for i in {1..30}; do
    if curl --silent --fail http://192.168.50.1/health >/dev/null; then
        echo "Provisioning server is ready."
        break
    fi

    sleep 1
done

echo
echo "Checking API health through nginx..."
curl --fail --show-error http://192.168.50.1/health
echo

echo
echo "Checking nginx landing page..."
curl --fail --show-error http://192.168.50.1/
echo

echo
echo "Checking dynamic iPXE response..."
curl --fail --show-error \
    'http://192.168.50.1/ipxe/boot?mac=c4:d6:d3:64:61:3e'
echo

###############################################################################
# 18. Verify bind mounts
###############################################################################

echo
echo "TFTP files visible inside dnsmasq:"
sudo docker exec proxmox-dnsmasq ls -lh /srv/tftp

echo
echo "HTTP files visible inside nginx:"
sudo docker exec proxmox-nginx find /usr/share/nginx/html \
    -maxdepth 3 -type f -print

###############################################################################
# 19. Final status
###############################################################################

cat <<EOF
Provisioning stack is ready.

Provisioning interface: ${LINK}
Provisioning address:   http://${PROVISION_IP}/
API health check:       http://${PROVISION_IP}/health
Dynamic iPXE endpoint:  http://${PROVISION_IP}/ipxe/boot?mac=<MAC>

Next PXE boot flow:

  Dell UEFI
    -> dnsmasq DHCP
    -> ipxe.efi over TFTP
    -> autoexec.ipxe over TFTP
    -> nginx on port 80
    -> Node.js /ipxe/boot endpoint
EOF


###############################################################################


# download iso
curl -LO http://download.proxmox.com/iso/proxmox-ve_9.2-1.iso
mv proxmox-ve_9.2-1.iso ./data/iso/


